export function wardrobe(
  temp: number,
  mode: string,
  wind: number,
  rain: number,
  uv?: number,
) {
  const active = mode === "active",
    cold = temp < 0,
    cool = temp < 12,
    warm = temp >= 23;
  const layers = [
    {
      label: "Базовый слой",
      item: warm
        ? "Лёгкое дышащее боди / футболка"
        : "Хлопковый лонгслив и брюки",
      icon: "👕",
    },
    {
      label: "Утепление",
      item:
        temp < 5
          ? "Флис или шерстяной средний слой"
          : temp < 18 && !active
            ? "Тонкая кофта"
            : "Дополнительный слой обычно не нужен",
      icon: temp < 18 ? "🧶" : "➖",
    },
    {
      label: "Верхняя одежда",
      item: cold
        ? "Утеплённый комбинезон"
        : rain > 0
          ? "Лёгкий непромокаемый верх"
          : cool || wind > 20
            ? "Ветрозащитная куртка"
            : warm
              ? "Открытая лёгкая одежда по условиям"
              : "Лёгкая куртка по ощущениям",
      icon: cold ? "🧥" : "🦺",
    },
    {
      label: "Ноги и обувь",
      item: cold
        ? "Тёплые носки и обувь / пинетки"
        : warm
          ? "Лёгкая обувь для ходьбы; младенцу по условиям"
          : "Носки и подходящая обувь; без тесного утепления",
      icon: "🧦",
    },
    {
      label: "Головной убор",
      item: warm
        ? "Панама на улице"
        : cool
          ? "Шапка по ветру и ощущениям"
          : "Лёгкий головной убор по солнцу/ветру",
      icon: warm ? "👒" : "🧢",
    },
    {
      label: "Дополнительно",
      item:
        rain > 0
          ? "Непромокаемая защита с вентиляцией"
          : warm || (uv ?? 0) >= 3
            ? "Тень, вода по возрасту, защита от солнца"
            : "Запасной слой, который можно снять",
      icon: rain > 0 ? "☂" : "🌤",
    },
  ];
  return {
    layers,
    warnings: [
      mode === "stroller"
        ? "Неподвижный малыш остывает быстрее активного. При необходимости добавьте съёмный слой, но не закрывайте лицо."
        : "При активной игре не перегревайте. Лишний слой снимайте по состоянию спины и шеи.",
      wind > 20
        ? "Сильный ветер усиливает охлаждение: выбирайте защищённый маршрут."
        : "",
      rain > 0
        ? "Не накрывайте коляску плотной тканью: она ухудшает вентиляцию."
        : "",
      temp >= 28
        ? "Жара: короткая прогулка в тени, без полуденного солнца."
        : "",
      temp < -10
        ? "Сильный холод: сократите выход, учитывайте ветер и обсудите особенности прогулок младенца с педиатром."
        : "",
      (uv ?? 0) >= 3
        ? "UV от 3: тень, закрывающая лёгкая одежда и подходящая защита; младенцам избегать прямого солнца."
        : "",
    ].filter(Boolean),
  };
}
