export function ageAdvice(month) {
  return month < 4
    ? "Короткие периоды бодрствования, контакт и безопасный сон важнее расписания."
    : month < 7
      ? "Давайте больше свободного движения на полу и разговаривайте в ответ на звуки."
      : month < 12
        ? "Обеспечьте безопасное пространство для перемещений. Обсудите прикорм и источники железа."
        : month < 24
          ? "Поддерживайте жесты и первые слова, самостоятельную еду и предсказуемые ритуалы."
          : "Играйте понарошку, читайте вместе и помогайте называть чувства.";
}
