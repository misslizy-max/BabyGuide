export const recipes: Recipe[] = rows.map(
  ([
    id,
    name,
    slot,
    minAge,
    minutes,
    icon,
    products,
    steps,
    regions,
    season,
  ]) => {
    const ingredients: Ingredient[] = products.map((p) => {
      const [key, grams] = p.split(":");
      return { id: key, name: foods[key].name, grams: Number(grams) };
    });
    return {
      id,
      name,
      slot,
      minAge,
      minutes,
      icon,
      ingredients,
      steps,
      allergens: [
        ...new Set(ingredients.flatMap((i) => foods[i.id].allergens || [])),
      ],
      texture:
        minAge < 8
          ? "Мягкое пюре или полностью размятая пища"
          : minAge < 12
            ? "Мягкая влажная пища с размятыми комочками по навыкам"
            : "Мягкие небольшие кусочки по навыкам жевания",
      serving: safeBase,
      substitutions:
        "Крупу можно заменить на уже знакомую рисовую или гречневую. Мясо — на другой переносимый источник белка. При аллергии выбирайте отдельный рецепт без аллергена: не удаляйте продукт из блюда без проверки остальных ингредиентов.",
      regions,
      seasons: season ? [season] : ["winter", "spring", "summer", "autumn"],
      vegetarian: !ingredients.some((i) =>
        ["turkey", "chicken", "beef", "fish", "salmon"].includes(i.id),
      ),
    };
  },
);
